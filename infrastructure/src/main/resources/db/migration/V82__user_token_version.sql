-- ===========================================================================
-- V82：JWT 主动撤销的版本号（安全基线）
-- ===========================================================================
--
-- 【为什么需要这一列】
-- 原 JWT 是无状态的：签名正确、未过期就放行，账号被禁用或用户点了"退出登录"
-- 之后旧令牌仍然有效，最长 8 小时。金融系统不能把撤权寄托在"令牌自己过期"上。
--
-- 做法：登录时把 users.token_version 写进 JWT 的 ver 声明；
-- 每次请求验签后回查该用户当前的 token_version，不相等即拒绝（AUTH_001）。
-- 退出登录 / 管理员强制下线 = token_version + 1，该账号**所有已签发令牌立即失效**。
--
-- 【为什么用版本号而不是令牌黑名单】
-- 黑名单需要按 jti 存一行并在过期后清理；版本号复用用户行，不需要清理，
-- 且天然支持"禁用账号立即失效"（verify 同时检查 enabled）。
-- 代价是退出登录会踢掉该账号的全部会话（单账号多设备场景）；这属于更安全一侧，
-- 若将来要按设备撤销，再引入 jti + 黑名单表。
--
-- 【兼容性】
-- 变更前签发的旧令牌没有 ver 声明，部署后会一律被判为失效（需重新登录）。
-- 这是刻意的安全默认值：宁可让用户重登一次，也不让无版本号的令牌继续通行。
-- ===========================================================================

ALTER TABLE users ADD COLUMN IF NOT EXISTS token_version INT NOT NULL DEFAULT 0;

COMMENT ON COLUMN users.token_version IS
    'JWT 撤销版本号：登录时写入 ver 声明；每次请求验签后回查，不等即失效。退出登录/强制下线 +1';
