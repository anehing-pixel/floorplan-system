package com.company.floorplan.domain.model;

/**
 * 担保方式（贴合日本新车渠道实务）。
 *
 * <p><b>日本新车渠道（品牌经销商 + 厂家金融）担保组合建议</b>：
 * <ul>
 *   <li><b>{@code ASSIGNMENT}（让与担保 / 譲渡担保）</b>——主担保方式。
 *       把车辆所有权以"担保为目的"移转给金融公司，并在
 *       <b>動産・債権譲渡登記</b>（动产·债权让渡登记）或自动车登记簿上公示，
 *       是日本库存融资最通行、对抗第三人最有效的担保形态。</li>
 *   <li><b>{@code RETENTION}（所有権留保）</b>——分期付款销售合同中的所有权保留条款，
 *       常作为 ASSIGNMENT 的补充（未上牌前尤其常用）。</li>
 *   <li><b>{@code MANUFACTURER_REPURCHASE}（メーカー買取約束 / 厂家回购承诺）</b>——
 *       日本新车渠道最核心的信用增强：经销商违约时，厂家按约定买回车辆，
 *       实质替代了部分"物理监管 + 强制收车"的作用。本系统把它登记为一类担保/增信。</li>
 *   <li><b>{@code OTHER}</b>——其他（如经销商信用、保证金等）。</li>
 *   <li><b>{@code NONE}</b>——无担保（极端情况留痕用）。</li>
 * </ul>
 *
 * <p><b>重要澄清（面向日本客户）</b>：中国第三方监管常见的
 * "扣押钥匙 / 装 GPS / 封签"等手段，<b>不适用于</b>日本厂家金融新车渠道——
 * 日本以"实地盘点 + 让与担保公示 + 厂家回购承诺"为主，不做强物理监管。
 * 因此本枚举不含物理监管类取值。</p>
 *
 * <p>系统默认担保方式见 {@code application.yml} 的 {@code floorplan.security.default-type}
 * （预设 {@code ASSIGNMENT}），可在"设定担保"接口显式覆盖。</p>
 */
public enum SecurityType {

    /** 让与担保（譲渡担保）—— 日本新车渠道主担保方式。 */
    ASSIGNMENT,
    /** 所有权保留（所有権留保）—— 分期销售合同中的保留条款。 */
    RETENTION,
    /** 厂家回购承诺（メーカー買取約束）—— 日本渠道核心信用增强。 */
    MANUFACTURER_REPURCHASE,
    /** 其他（经销商信用 / 保证金等）。 */
    OTHER,
    /** 无担保（留痕用）。 */
    NONE
}
